let firstname = "Arefin";
let lastname = "Ahmed";
// 1. Concatenation
let fullname = firstname + " " + lastname;
console.log(fullname);

let fullname2 = `${firstname} ${lastname}`;
console.log(fullname2);

let fullname3 = `${firstname} ${lastname} is a good boy`;
console.log(fullname3);

let fullname4 = `${firstname} ${lastname} \nBangladesh`;
console.log(fullname4);

// 2. Escape character
let random = "I am a \"student\"";
console.log(random);

// or

let random2 = 'I am a "student"';
console.log(random2);